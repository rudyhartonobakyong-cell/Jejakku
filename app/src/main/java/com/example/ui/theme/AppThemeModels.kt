package com.example.ui.theme

import androidx.compose.material3.ColorScheme
import androidx.compose.material3.darkColorScheme
import androidx.compose.material3.lightColorScheme
import androidx.compose.ui.graphics.Color

enum class AppThemeId(val storageKey: String) {
  SAMUDRA("samudra"),
  PINK_MANIS("pink_manis"),
  HITAM_ELEGAN("hitam_elegan"),
  HIJAU_HUTAN("hijau_hutan"),
  UNGU_SENJA("ungu_senja"),
  ORANYE_PANTAI("oranye_pantai");

  companion object {
    fun fromKey(key: String?): AppThemeId =
      entries.firstOrNull { it.storageKey == key } ?: SAMUDRA
  }
}

data class AppThemeSpec(
  val id: AppThemeId,
  val displayName: String,
  val isDark: Boolean,
  val background: Color,
  val accent: Color,
  val surface: Color,
  val surfaceVariant: Color,
  val surfaceContainer: Color,
  val onBackground: Color,
  val onSurfaceVariant: Color,
  val onPrimary: Color,
  val primaryContainer: Color,
  val onPrimaryContainer: Color,
  val outline: Color,
  val error: Color,
  val onError: Color,
) {
  fun toColorScheme(): ColorScheme =
    if (isDark) {
      darkColorScheme(
        primary = accent,
        onPrimary = onPrimary,
        primaryContainer = primaryContainer,
        onPrimaryContainer = onPrimaryContainer,
        secondary = accent.copy(alpha = 0.85f),
        onSecondary = onPrimary,
        secondaryContainer = surfaceVariant,
        onSecondaryContainer = onBackground,
        tertiary = accent,
        onTertiary = onPrimary,
        background = background,
        onBackground = onBackground,
        surface = surface,
        onSurface = onBackground,
        surfaceVariant = surfaceVariant,
        onSurfaceVariant = onSurfaceVariant,
        surfaceContainerLowest = background,
        surfaceContainerLow = surface,
        surfaceContainer = surfaceContainer,
        surfaceContainerHigh = surfaceVariant,
        surfaceContainerHighest = surfaceVariant,
        outline = outline,
        outlineVariant = outline.copy(alpha = 0.6f),
        error = error,
        onError = onError,
      )
    } else {
      lightColorScheme(
        primary = accent,
        onPrimary = onPrimary,
        primaryContainer = primaryContainer,
        onPrimaryContainer = onPrimaryContainer,
        secondary = accent.copy(alpha = 0.85f),
        onSecondary = onPrimary,
        secondaryContainer = surfaceVariant,
        onSecondaryContainer = onBackground,
        tertiary = accent,
        onTertiary = onPrimary,
        background = background,
        onBackground = onBackground,
        surface = surface,
        onSurface = onBackground,
        surfaceVariant = surfaceVariant,
        onSurfaceVariant = onSurfaceVariant,
        surfaceContainerLowest = surface,
        surfaceContainerLow = surface,
        surfaceContainer = surfaceContainer,
        surfaceContainerHigh = surfaceVariant,
        surfaceContainerHighest = surfaceVariant,
        outline = outline,
        outlineVariant = outline.copy(alpha = 0.6f),
        error = error,
        onError = onError,
      )
    }
}

